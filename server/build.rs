//! Embeds the web app (`web/build`, made by `npm run build` in `web/`) into
//! the faro-server binary, so an instance serves it from its own origin with
//! no files to install (ARCHITECTURE.md §4.5).
//!
//! Writes `$OUT_DIR/web_bundle.rs`: a table of every file with its media type,
//! its bytes (`include_bytes!`) and, for HTML pages, the CSP hashes of the
//! page's inline scripts (SvelteKit starts each page with one), so the
//! server's CSP can forbid every other inline script. Likewise
//! `STYLE_ATTR_HASHES` holds the hashes of the constant `style="…"`
//! attributes in the compiled templates (SvelteKit's route announcer has
//! one), which `style-src-attr 'unsafe-hashes'` then allows and nothing else.
//!
//! Cargo never runs npm. Without `web/build` the table is empty and the
//! server answers page requests with a short note saying so; the API is
//! unaffected. Release builds (the container image, CI's web job) set
//! `FARO_REQUIRE_WEB=1`, which turns a missing bundle into a build error.
//! `FARO_WEB_DIR` points at a bundle somewhere else.

use base64::Engine as _;
use sha2::{Digest, Sha256};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    println!("cargo:rerun-if-env-changed=FARO_WEB_DIR");
    println!("cargo:rerun-if-env-changed=FARO_REQUIRE_WEB");

    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let web_dir = env::var_os("FARO_WEB_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest_dir.join("../web/build"));
    let required = env::var("FARO_REQUIRE_WEB").is_ok_and(|v| v == "1");

    let mut files = Vec::new();
    if web_dir.is_dir() {
        println!("cargo:rerun-if-changed={}", web_dir.display());
        collect(&web_dir, &web_dir, &mut files);
        files.sort_by(|a, b| a.0.cmp(&b.0));
    } else {
        // Notice when `npm run build` creates the bundle. Cargo scans a
        // directory recursively, so this also covers web/build appearing.
        println!(
            "cargo:rerun-if-changed={}",
            manifest_dir.join("../web").display()
        );
    }

    if required {
        for page in [
            "index.html",
            "setup.html",
            "signin.html",
            "auth/verify.html",
            "invite.html",
            "admin.html",
            "admin/people.html",
            "admin/settings.html",
            "admin/email.html",
            "404.html",
        ] {
            assert!(
                files.iter().any(|(rel, _)| rel == page),
                "FARO_REQUIRE_WEB=1 but {} has no {page}: run `npm ci && npm run build` in web/",
                web_dir.display()
            );
        }
    }

    let mut style_attrs = Vec::new();
    let mut out = String::from(
        "// @generated by server/build.rs from the web app bundle.\n\
         pub static FILES: &[crate::web::EmbeddedFile] = &[\n",
    );
    for (rel, abs) in &files {
        if rel.ends_with(".js") {
            let js = fs::read_to_string(abs).unwrap_or_else(|e| panic!("{}: {e}", abs.display()));
            style_attrs.extend(constant_style_attrs(&js).into_iter().map(|v| csp_hash(&v)));
        }
        let content_type = content_type(rel);
        let hashes = if rel.ends_with(".html") {
            let html = fs::read_to_string(abs).unwrap_or_else(|e| panic!("{}: {e}", abs.display()));
            inline_script_hashes(&html)
        } else {
            Vec::new()
        };
        let abs = abs
            .canonicalize()
            .unwrap_or_else(|e| panic!("{}: {e}", abs.display()));
        writeln!(
            out,
            "    crate::web::EmbeddedFile {{ path: {rel:?}, content_type: {content_type:?}, \
             bytes: include_bytes!({:?}), inline_script_hashes: &{hashes:?} }},",
            abs.display().to_string()
        )
        .unwrap();
    }
    out.push_str("];\n");
    style_attrs.sort();
    style_attrs.dedup();
    writeln!(
        out,
        "pub static STYLE_ATTR_HASHES: &[&str] = &{style_attrs:?};"
    )
    .unwrap();

    let dest = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("web_bundle.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}

/// Every regular file under `dir`, as (path relative to `root` with `/`
/// separators, absolute path). Skips precompressed copies and dotfiles.
fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.expect("read_dir entry").path())
        .collect();
    entries.sort();
    for path in entries {
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_default();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect(root, &path, files);
        } else if path.is_file() && !name.ends_with(".gz") && !name.ends_with(".br") {
            let rel = path
                .strip_prefix(root)
                .expect("under root")
                .components()
                .map(|c| {
                    c.as_os_str()
                        .to_str()
                        .expect("UTF-8 file name in web bundle")
                })
                .collect::<Vec<_>>()
                .join("/");
            files.push((rel, path));
        }
    }
}

fn content_type(path: &str) -> &'static str {
    match path.rsplit_once('.').map(|(_, ext)| ext) {
        Some("html") => "text/html; charset=utf-8",
        Some("js" | "mjs") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("webp") => "image/webp",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("woff") => "font/woff",
        Some("txt") => "text/plain; charset=utf-8",
        Some("webmanifest") => "application/manifest+json",
        Some("wasm") => "application/wasm",
        _ => "application/octet-stream",
    }
}

/// CSP source expressions (`'sha256-…'`) for each inline `<script>` in a
/// page. A script with a `src` attribute is not inline and needs no hash.
///
/// This is a scanner for SvelteKit's own output, not a general HTML parser:
/// it finds `<script ...>` open tags and hashes the exact text up to the next
/// `</script>`, which is what the browser hashes.
fn inline_script_hashes(html: &str) -> Vec<String> {
    let mut hashes = Vec::new();
    let mut rest = html;
    while let Some(start) = rest.find("<script") {
        rest = &rest[start + "<script".len()..];
        let Some(tag_end) = rest.find('>') else { break };
        let attrs = &rest[..tag_end];
        rest = &rest[tag_end + 1..];
        let Some(close) = rest.find("</script>") else {
            break;
        };
        let body = &rest[..close];
        rest = &rest[close + "</script>".len()..];
        if attrs.contains("src=") {
            continue;
        }
        hashes.push(csp_hash(body));
    }
    hashes
}

/// The constant values of `style="…"` attributes in compiled Svelte
/// templates, which appear in the JS as HTML strings. A value with template
/// interpolation (`${`) or escapes is dynamic and left out: the browser
/// blocks it, so components set dynamic styles with `style:` (the CSSOM),
/// which CSP does not restrict.
fn constant_style_attrs(js: &str) -> Vec<String> {
    let mut values = Vec::new();
    let mut rest = js;
    while let Some(start) = rest.find("style=\"") {
        rest = &rest[start + "style=\"".len()..];
        let Some(end) = rest.find('"') else { break };
        let value = &rest[..end];
        rest = &rest[end + 1..];
        if !value.is_empty() && !value.contains("${") && !value.contains('\\') {
            values.push(value.to_owned());
        }
    }
    values
}

/// A CSP hash source: `'sha256-<base64>'`.
fn csp_hash(text: &str) -> String {
    format!(
        "'sha256-{}'",
        base64::engine::general_purpose::STANDARD.encode(Sha256::digest(text.as_bytes()))
    )
}
